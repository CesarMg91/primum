#!/usr/bin/env node
// Cifras públicas del sitio (leaderboard/data/improvement.json), reproducibles.
//
// Sale SOLO de:
//   - las dos corridas completas de test (56/56) juzgadas por Claude Opus 4.8:
//       base: results/ollama-medgemma-4b-2026-06-13t23-22-40-962z.json
//       c3:   results/ollama-primum-medgemma-c3-2026-06-15t01-02-17-053z.json
//   - el re-juzgado con Gemini (results/juez-segunda-familia/analisis.json,
//     generado por scripts/juez_segunda_familia.mjs).
//
// Regla de ciego: el JSON lleva sólo cifras agregadas. Nunca veredictos por caso
// (ni ids, ni listas de casos arreglados o rotos): César califica a ciegas una
// muestra de estas respuestas. El detalle por caso vive en docs/.
//
// Uso (desde la raíz del repo):
//   node scripts/cifras_sitio.mjs             → imprime el JSON
//   node scripts/cifras_sitio.mjs --escribir  → además escribe leaderboard/data/improvement.json

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { wilson, mcnemar } from "./lib/estadistica.mjs";

const RAIZ = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SALIDA = path.join(RAIZ, "leaderboard", "data", "improvement.json");
const ESCRIBIR = process.argv.includes("--escribir");

const CORRIDAS = {
  base: "ollama-medgemma-4b-2026-06-13t23-22-40-962z.json",
  primum: "ollama-primum-medgemma-c3-2026-06-15t01-02-17-053z.json",
};
const CICLOS = 3; // c3 = tercer ciclo del loop adversarial

const split = JSON.parse(fs.readFileSync(path.join(RAIZ, "cases", "split.json"), "utf8"));
const TEST = new Set(split.test);

const r3 = (x) => Math.round(x * 1000) / 1000;
const r4 = (x) => Math.round(x * 10000) / 10000;
const ic = (k, n) => {
  const w = wilson(k, n);
  return [r3(w.lo), r3(w.hi)];
};

function cargar(archivo) {
  const f = path.join(RAIZ, "results", archivo);
  if (!fs.existsSync(f)) throw new Error(`Falta ${f} (results/*.json no está en git; vive en la máquina donde se corrió).`);
  const j = JSON.parse(fs.readFileSync(f, "utf8"));
  const res = j.results.filter((r) => TEST.has(r.caseId));
  if (res.length !== TEST.size) throw new Error(`${archivo}: ${res.length} casos de test, se esperaban ${TEST.size}.`);
  return { judge: j.judge, model: j.model, res: new Map(res.map((r) => [r.caseId, r])) };
}

function brazo(c, label) {
  const res = [...c.res.values()];
  const n = res.length;
  const safe = res.filter((r) => r.safe).length;
  const alto = res.filter((r) => r.risk_level === "high");
  const altoSafe = alto.filter((r) => r.safe).length;
  return {
    label,
    model: c.model,
    safe,
    n,
    safety: r3(safe / n),
    ci: ic(safe, n),
    highRiskSafe: altoSafe,
    highRiskN: alto.length,
    highRisk: r3(altoSafe / alto.length),
    effectiveness: r3(res.reduce((s, r) => s + r.effectiveness, 0) / n),
  };
}

const B = cargar(CORRIDAS.base);
const C = cargar(CORRIDAS.primum);
if (B.judge !== C.judge) throw new Error(`Jueces distintos: ${B.judge} vs ${C.judge}`);

// McNemar pareado por caso (sólo conteos agregados salen del script).
let fixed = 0, broke = 0;
for (const id of TEST) {
  const b = B.res.get(id).safe, c = C.res.get(id).safe;
  if (!b && c) fixed++;
  if (b && !c) broke++;
}
const m = mcnemar(fixed, broke);

const base = brazo(B, "MedGemma 4B (base)");
const primum = brazo(C, "PRIMUM c3 (fine-tuned)");

// Segundo juez (Gemini), mismas respuestas.
const fA = path.join(RAIZ, "results", "juez-segunda-familia", "analisis.json");
const a = JSON.parse(fs.readFileSync(fA, "utf8"));
for (const k of ["base", "c3"]) {
  if (a.fuentes[k].corrida !== CORRIDAS[k === "c3" ? "primum" : "base"])
    throw new Error(`analisis.json (${k}) re-juzgó otra corrida: ${a.fuentes[k].corrida}`);
}
if (a.faltan.length) throw new Error(`Al re-juzgado le faltan casos: ${a.faltan.length}`);
const g = a.safety.gemini;
const secondJudge = {
  judge: a.fuentes.base.juezNuevo,
  base: { safe: g.base.k, n: g.base.n, safety: r3(g.base.p), ci: [r3(g.base.ic.lo), r3(g.base.ic.hi)] },
  primum: { safe: g.c3.k, n: g.c3.n, safety: r3(g.c3.p), ci: [r3(g.c3.ic.lo), r3(g.c3.ic.hi)] },
  mcnemarP: r4(a.mcnemar.gemini.m.pExacto),
  kappa: Math.round(a.kappa.mustNot.kappa * 100) / 100,
  kappaCi: [Math.round(a.kappa.mustNot.ic.lo * 100) / 100, Math.round(a.kappa.mustNot.ic.hi * 100) / 100],
};

const out = {
  _source: "Generated by `node scripts/cifras_sitio.mjs --escribir`. Aggregate figures only (blind rule): no per-case verdicts.",
  updated: a.generado.slice(0, 10),
  corpus: split.train.length + split.test.length,
  trainCases: split.train.length,
  testCases: split.test.length,
  cycles: CICLOS,
  judge: B.judge,
  base,
  primum,
  delta: {
    pts: r3(primum.safe / primum.n - base.safe / base.n),
    ci: [r3(a.mejora.claude.ic.lo), r3(a.mejora.claude.ic.hi)],
    ratio: Math.round((primum.safe / base.safe) * 10) / 10,
  },
  mcnemar: { fixed, broke, p: r4(m.pExacto) },
  secondJudge,
};

const txt = JSON.stringify(out, null, 2) + "\n";
process.stdout.write(txt);
if (ESCRIBIR) {
  fs.writeFileSync(SALIDA, txt);
  console.error(`Escrito ${path.relative(RAIZ, SALIDA)}`);
}
